//! A world-agnostic host kit for running WebAssembly components in a
//! wasmtime sandbox.
//!
//! This crate knows nothing about JavaScript or any particular WIT world. It
//! takes a component, your host imports and your own state, and looks after
//! the parts every embedder ends up writing:
//!
//! - **Compile cache**: native code is cached on disk, keyed by content and
//!   engine configuration, so a large component starts in milliseconds
//!   instead of tens of seconds.
//! - **Deadlines**: each call into the guest has a wall-clock budget that
//!   holds whether the guest is spinning or waiting on I/O.
//! - **Fair scheduling**: guests run as ordinary async tasks and yield to
//!   the executor every few milliseconds; no thread per guest.
//! - **Limits**: a hard cap on linear memory (with out-of-memory detection),
//!   optional fuel, and capped console capture.
//! - **Isolation**: a fresh store per [`Session`], WASI with everything off
//!   by default, and optionally deterministic clocks and randomness.
//! - **Egress** (feature `http`, on by default): outgoing `wasi:http`
//!   requests go through a [`codelib_http::Egress`]; without one, every
//!   request is denied.
//! - **WASI 0.3** (feature `p3`, off by default): components built against
//!   WASI 0.3 run alongside 0.2 ones, with the same guarantees; see
//!   [below](#wasi-03).
//!
//! The ready-made JavaScript sandbox built on top of this lives in the
//! `codelib` crate. Use this crate directly to host a different world:
//!
//! ```no_run
//! use codelib_sandbox::{Limits, Runtime, SessionOptions};
//! use std::time::Duration;
//!
//! # async fn demo() -> Result<(), Box<dyn std::error::Error>> {
//! let runtime = Runtime::<()>::builder()
//!     .component_file("my-component.wasm")
//!     .limits(Limits::default().timeout(Duration::from_secs(5)))
//!     // .link(|linker| my_world::add_to_linker(linker, |ctx| &mut ctx.state))
//!     .build()?;
//!
//! let mut session = runtime.session(SessionOptions::new(())).await?;
//! let sum = session
//!     .call(async |store, instance| {
//!         let add = instance.get_typed_func::<(u32, u32), (u32,)>(&mut *store, "add")?;
//!         let (sum,) = add.call_async(&mut *store, (1, 2)).await?;
//!         Ok(sum)
//!     })
//!     .await?;
//! assert_eq!(sum, 3);
//! # Ok(()) }
//! ```
//!
//! # WASI 0.3
//!
//! With the `p3` feature the engine accepts the async component model, and
//! the WASI 0.3 interfaces (`wasi:cli`, `wasi:clocks`, `wasi:random`,
//! `wasi:filesystem`, `wasi:sockets` at `@0.3.0`, and `wasi:http` 0.3 with
//! the `http` feature) are linked next to the 0.2 ones. One runtime hosts
//! 0.2 components, 0.3 components, and components that import both (a Rust
//! guest's standard library still uses 0.2). Both versions are served from
//! the same per-session state, so the console capture, [`WasiConfig`]
//! (environment, arguments, frozen clocks, seeded randomness) and the
//! session's egress apply to 0.3 guests unchanged, and the filesystem and
//! sockets stay closed.
//!
//! [`Session::call`] runs a 0.3 component's exports, async ones included,
//! one at a time. `Session::call_concurrent` hands the closure an
//! [`Accessor`](wasmtime::component::Accessor) instead of the store, so it
//! can start several export calls and let the guest interleave them, under
//! one time budget and one fuel tank:
//!
//! ```ignore
//! let (a, b) = session
//!     .call_concurrent(async |accessor, instance| {
//!         // Generated by `bindgen!` with `exports: { default: async | store }`.
//!         let world = accessor.with(|mut store| MyWorld::new(&mut store, instance))?;
//!         let (a, b) = tokio::join!(world.call_fetch(accessor, 1), world.call_fetch(accessor, 2));
//!         Ok((a?, b?))
//!     })
//!     .await?;
//! ```
//!
//! wasmtime marks its 0.3 support experimental, and so does this crate:
//! it follows whatever wasmtime version this crate depends on.

