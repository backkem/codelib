/// TypeScript declarations for the client [`js_client`] generates:
/// `declare const <global>: { ... };`.
///
/// Best effort: argument and result types come from the JSON Schemas when present (objects,
/// arrays, tuples, primitives, enums, consts, unions, optional fields, local `$ref`s);
/// otherwise `unknown`. The argument is optional when its schema accepts `null` or an object
/// without required fields (the empty-args rule), or when there is no schema. A `global` that is
/// not an identifier has its invalid characters replaced by `_`, and a reserved word gets a `_`
/// prefix. Shared `$ref`s are rendered once; a nested `$ref` whose expansion exceeds 4 KiB
/// becomes `unknown`, which bounds the output of schemas that reuse definitions heavily.
pub fn typescript<'a>(
    methods: impl IntoIterator<Item = &'a MethodInfo>,
    opts: &JsOptions,
) -> String {
    let tree = Node::build(methods);
    let global: String = opts
        .global
        .chars()
        .enumerate()
        .map(|(i, c)| {
            if (c.is_ascii_alphanumeric() && !(i == 0 && c.is_ascii_digit()))
                || c == '_'
                || c == '$'
            {
                c
            } else {
                '_'
            }
        })
        .collect();
    let global = if global.is_empty() {
        "api".to_owned()
    } else if TS_RESERVED.contains(&global.as_str()) {
        format!("_{global}")
    } else {
        global
    };
    let mut out = String::from(HEADER);
    let _ = write!(out, "declare const {global}: ");
    ts_object(&mut out, &tree, opts, 0);
    out.push_str(";\n");
    out
}

fn ts_object(out: &mut String, node: &Node<'_>, opts: &JsOptions, depth: usize) {
    if node.method.is_none() && node.children.is_empty() {
        out.push_str("{}");
        return;
    }
    let indent = "  ".repeat(depth + 1);
    out.push_str("{\n");
    if let Some(m) = node.method {
        // A method that is also a namespace: a call signature.
        let _ = writeln!(out, "{indent}{};", ts_signature(m, opts));
    }
    for (key, child) in &node.children {
        let key = ts_member_key(key);
        if let Some(m) = child.method {
            let mut lines = vec![m.summary.clone()];
            if let Some(a) = &m.args {
                lines.push(format!("args: {a}"));
            }
            if let Some(r) = &m.returns {
                lines.push(format!("returns: {r}"));
            }
            doc_comment(out, &indent, &lines);
        }
        match (child.method, child.children.is_empty()) {
            (Some(m), true) => {
                let _ = writeln!(out, "{indent}{key}{};", ts_signature(m, opts));
            }
            _ => {
                let _ = write!(out, "{indent}{key}: ");
                ts_object(out, child, opts, depth + 1);
                out.push_str(";\n");
            }
        }
    }
    let _ = write!(out, "{}}}", "  ".repeat(depth));
}

/// `(args: A): R` for one method.
fn ts_signature(m: &MethodInfo, opts: &JsOptions) -> String {
    let (args, optional) = match &m.args_schema {
        Some(s) => (schema_to_ts(s), accepts_nothing(s, s, 0)),
        None => ("unknown".to_owned(), true),
    };
    let returns = m
        .returns_schema
        .as_ref()
        .map(schema_to_ts)
        .unwrap_or_else(|| "unknown".to_owned());
    let returns = if opts.promise {
        format!("Promise<{returns}>")
    } else {
        returns
    };
    let q = if optional { "?" } else { "" };
    format!("(args{q}: {args}): {returns}")
}

/// A TypeScript type for a JSON Schema (draft 7 or 2020-12), best effort.
pub fn schema_to_ts(schema: &Value) -> String {
    Ts {
        root: schema,
        stack: Vec::new(),
        cache: HashMap::new(),
        cuts: 0,
    }
    .render(schema)
}

struct Ts<'a> {
    root: &'a Value,
    stack: Vec<&'a str>,
    /// Finished expansions of `$ref`s, so a definition used many times is rendered once.
    cache: HashMap<&'a str, String>,
    /// How many times an expansion was cut short because of the stack (cycle or depth). A
    /// result produced with cuts depends on where it was reached from and is not cached.
    cuts: usize,
}

const MAX_DEPTH: usize = 32;

/// Longest expansion of a nested `$ref`, in bytes; a longer one becomes `unknown`.
const MAX_REF_LEN: usize = 4096;

impl<'a> Ts<'a> {
    fn render(&mut self, schema: &'a Value) -> String {
        if self.stack.len() > MAX_DEPTH {
            self.cuts += 1;
            return "unknown".to_owned();
        }
        let o = match schema {
            Value::Bool(true) => return "unknown".to_owned(),
            Value::Bool(false) => return "never".to_owned(),
            Value::Object(o) => o,
            _ => return "unknown".to_owned(),
        };
        if let Some(r) = o.get("$ref").and_then(Value::as_str) {
            if self.stack.contains(&r) {
                self.cuts += 1;
                return "unknown".to_owned();
            }
            if let Some(t) = self.cache.get(r) {
                return t.clone();
            }
            let Some(target) = resolve_ref(self.root, r) else {
                return "unknown".to_owned();
            };
            let nested = !self.stack.is_empty();
            let cuts = self.cuts;
            self.stack.push(r);
            let mut t = self.render(target);
            self.stack.pop();
            if nested && t.len() > MAX_REF_LEN {
                t = "unknown".to_owned();
            }
            if self.cuts == cuts {
                self.cache.insert(r, t.clone());
            }
            return t;
        }
        let t = self.render_inner(o);
        if o.get("nullable").and_then(Value::as_bool) == Some(true) {
            union([t, "null".to_owned()])
        } else {
            t
        }
    }

    fn render_inner(&mut self, o: &'a Map<String, Value>) -> String {
        if let Some(c) = o.get("const") {
            return literal(c);
        }
        if let Some(Value::Array(values)) = o.get("enum") {
            return union(values.iter().map(literal));
        }
        for key in ["anyOf", "oneOf"] {
            if let Some(Value::Array(alts)) = o.get(key) {
                let alts: Vec<String> = alts.iter().map(|s| self.render(s)).collect();
                return union(alts);
            }
        }
        if let Some(Value::Array(all)) = o.get("allOf") {
            let parts: Vec<String> = all.iter().map(|s| self.render(s)).collect();
            return match parts.as_slice() {
                [one] => one.clone(),
                _ => format!(
                    "({})",
                    parts
                        .iter()
                        .map(|p| wrap(p))
                        .collect::<Vec<_>>()
                        .join(" & ")
                ),
            };
        }
        match o.get("type") {
            Some(Value::String(t)) => self.typed(t, o),
            Some(Value::Array(ts)) => {
                let parts: Vec<String> = ts
                    .iter()
                    .filter_map(Value::as_str)
                    .map(|t| self.typed(t, o))
                    .collect();
                union(parts)
            }
            _ if o.contains_key("properties") || o.contains_key("additionalProperties") => {
                self.typed("object", o)
            }
            _ if o.contains_key("items") || o.contains_key("prefixItems") => self.typed("array", o),
            _ => "unknown".to_owned(),
        }
    }

    fn typed(&mut self, ty: &str, o: &'a Map<String, Value>) -> String {
        match ty {
            "string" => "string".to_owned(),
            "number" | "integer" => "number".to_owned(),
            "boolean" => "boolean".to_owned(),
            "null" => "null".to_owned(),
            "array" => self.array(o),
            "object" => self.object(o),
            _ => "unknown".to_owned(),
        }
    }

    fn array(&mut self, o: &'a Map<String, Value>) -> String {
        let tuple = match (o.get("prefixItems"), o.get("items")) {
            (Some(Value::Array(items)), _) | (None, Some(Value::Array(items))) => Some(items),
            _ => None,
        };
        if let Some(items) = tuple {
            let parts: Vec<String> = items.iter().map(|s| self.render(s)).collect();
            return format!("[{}]", parts.join(", "));
        }
        let Some(items) = o.get("items") else {
            return "unknown[]".to_owned();
        };
        let item = self.render(items);
        // A fixed, small length (`[f64; 2]`) reads better as a tuple.
        let min = o.get("minItems").and_then(Value::as_u64);
        let max = o.get("maxItems").and_then(Value::as_u64);
        match (min, max) {
            (Some(n), Some(m)) if n == m && (1..=8).contains(&n) => {
                format!("[{}]", vec![item; n as usize].join(", "))
            }
            _ => format!("{}[]", wrap(&item)),
        }
    }

    fn object(&mut self, o: &'a Map<String, Value>) -> String {
        let required: Vec<&str> = match o.get("required") {
            Some(Value::Array(r)) => r.iter().filter_map(Value::as_str).collect(),
            _ => Vec::new(),
        };
        let extra = match o.get("additionalProperties") {
            None | Some(Value::Bool(true)) => Some("unknown".to_owned()),
            Some(Value::Bool(false)) => None,
            Some(s) => Some(self.render(s)),
        };
        match o.get("properties") {
            Some(Value::Object(props)) if !props.is_empty() => {
                let mut fields: Vec<String> = props
                    .iter()
                    .map(|(k, s)| {
                        let q = if required.contains(&k.as_str()) {
                            ""
                        } else {
                            "?"
                        };
                        format!("{}{q}: {}", property_key(k), self.render(s))
                    })
                    .collect();
                if o.get("additionalProperties")
                    .is_some_and(|a| a != &Value::Bool(false))
                {
                    fields.push("[key: string]: unknown".to_owned());
                }
                format!("{{ {} }}", fields.join("; "))
            }
            Some(Value::Object(_)) if extra.is_none() => "{}".to_owned(),
            _ => match extra {
                Some(t) => format!("Record<string, {t}>"),
                None => "{}".to_owned(),
            },
        }
    }
}

fn resolve_ref<'a>(root: &'a Value, r: &str) -> Option<&'a Value> {
    let pointer = r.strip_prefix('#')?;
    if pointer.is_empty() {
        return None; // The root itself: recursive.
    }
    root.pointer(pointer)
}

fn literal(v: &Value) -> String {
    match v {
        Value::String(_) | Value::Number(_) | Value::Bool(_) | Value::Null => v.to_string(),
        _ => "unknown".to_owned(),
    }
}

fn union(parts: impl IntoIterator<Item = String>) -> String {
    let mut seen: Vec<String> = Vec::new();
    for p in parts {
        if p == "unknown" {
            return "unknown".to_owned();
        }
        if !seen.contains(&p) {
            seen.push(p);
        }
    }
    match seen.len() {
        0 => "never".to_owned(),
        _ => seen.join(" | "),
    }
}

/// Whether the `(` at the start of `t` is closed by the `)` at its very end, so `(A) | (B)`
/// (whose outer characters are parentheses that do not match each other) is not.
fn is_parenthesized(t: &str) -> bool {
    if !(t.starts_with('(') && t.ends_with(')')) {
        return false;
    }
    let mut depth = 0usize;
    let mut in_string = false;
    let mut escaped = false;
    for (i, c) in t.char_indices() {
        if in_string {
            match (escaped, c) {
                (true, _) => escaped = false,
                (false, '\\') => escaped = true,
                (false, '"') => in_string = false,
                _ => {}
            }
            continue;
        }
        match c {
            '"' => in_string = true,
            '(' => depth += 1,
            ')' => {
                depth = depth.saturating_sub(1);
                if depth == 0 {
                    return i + 1 == t.len();
                }
            }
            _ => {}
        }
    }
    false
}

/// Parenthesizes a union for use as an array element.
fn wrap(t: &str) -> String {
    if t.contains(" | ") && !is_parenthesized(t) {
        format!("({t})")
    } else {
        t.to_owned()
    }
}

/// Whether a schema accepts "no arguments": `null` or an object without required fields.
fn accepts_nothing(schema: &Value, root: &Value, depth: usize) -> bool {
    if depth > MAX_DEPTH {
        return false;
    }
    let o = match schema {
        Value::Bool(b) => return *b,
        Value::Object(o) => o,
        _ => return false,
    };
    if let Some(r) = o.get("$ref").and_then(Value::as_str) {
        return resolve_ref(root, r).is_some_and(|t| accepts_nothing(t, root, depth + 1));
    }
    if o.get("nullable").and_then(Value::as_bool) == Some(true) {
        return true;
    }
    if let Some(c) = o.get("const") {
        return c.is_null();
    }
    if let Some(Value::Array(values)) = o.get("enum") {
        return values.iter().any(Value::is_null);
    }
    for key in ["anyOf", "oneOf"] {
        if let Some(Value::Array(alts)) = o.get(key) {
            return alts.iter().any(|s| accepts_nothing(s, root, depth + 1));
        }
    }
    if let Some(Value::Array(all)) = o.get("allOf") {
        return all.iter().all(|s| accepts_nothing(s, root, depth + 1));
    }
    let types: Vec<&str> = match o.get("type") {
        Some(Value::String(t)) => vec![t.as_str()],
        Some(Value::Array(ts)) => ts.iter().filter_map(Value::as_str).collect(),
        _ if o.contains_key("properties") => vec!["object"],
        _ => return o.is_empty(),
    };
    types.iter().any(|&t| {
        t == "null"
            || (t == "object"
                && match o.get("required") {
                    Some(Value::Array(r)) => r.is_empty(),
                    _ => true,
                })
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn identifiers_and_keys() {
        assert!(is_identifier("addLine"));
        assert!(is_identifier("$x_1"));
        assert!(!is_identifier("frame-fix"));
        assert!(!is_identifier("1a"));
        assert!(!is_identifier(""));
        assert_eq!(property_key("frame-fix"), "\"frame-fix\"");
        assert_eq!(property_key("__proto__"), "[\"__proto__\"]");
        assert_eq!(property_key("delete"), "delete");
    }

    #[test]
    fn code_spans() {
        assert_eq!(code_span("{a, b}"), "`{a, b}`");
        assert_eq!(code_span("a`b"), "`` a`b ``");
        assert_eq!(code_span("a\n  b"), "`a b`");
    }

    #[test]
    fn doc_comments_are_defused() {
        let mut out = String::new();
        doc_comment(&mut out, "", &["ends */ here".to_owned()]);
        assert_eq!(out, "/** ends *\\/ here */\n");
    }

    #[test]
    fn schema_types() {
        // Keys are in alphabetical order so the expectation holds with and without
        // serde_json's `preserve_order`.
        let s = json!({
            "type": "object",
            "properties": {
                "either": {"anyOf": [{"type": "string"}, {"type": "array", "items": {"type": ["integer", "null"]}}]},
                "inner": {"$ref": "#/$defs/Inner"},
                "kind": {"enum": ["outer", "inner"]},
                "layer": {"type": ["string", "null"]},
                "map": {"type": "object", "additionalProperties": {"type": "boolean"}},
                "odd-key": {"const": 3},
                "pair": {"type": "array", "prefixItems": [{"type": "integer"}, {"type": "string"}]},
                "start": {"type": "array", "items": {"type": "number"}}
            },
            "required": ["start", "kind"],
            "$defs": {"Inner": {"type": "object", "properties": {"x": {"type": "number"}}, "required": ["x"]}}
        });
        assert_eq!(
            schema_to_ts(&s),
            "{ either?: string | (number | null)[]; inner?: { x: number }; \
             kind: \"outer\" | \"inner\"; layer?: string | null; map?: Record<string, boolean>; \
             \"odd-key\"?: 3; pair?: [number, string]; start: number[] }"
        );
        assert!(!accepts_nothing(&s, &s, 0));
        assert!(accepts_nothing(&json!({"type": "null"}), &json!({}), 0));
        assert!(accepts_nothing(
            &json!({"type": "object", "properties": {"a": {"type": "string"}}}),
            &json!({}),
            0
        ));
    }

    #[test]
    fn recursive_refs_become_unknown() {
        let s = json!({
            "$ref": "#/$defs/Tree",
            "$defs": {"Tree": {"type": "object", "properties": {"kids": {"type": "array", "items": {"$ref": "#/$defs/Tree"}}}, "required": ["kids"]}}
        });
        assert_eq!(schema_to_ts(&s), "{ kids: unknown[] }");
        assert_eq!(schema_to_ts(&json!({"$ref": "#"})), "unknown");
        assert_eq!(schema_to_ts(&json!(true)), "unknown");
        assert_eq!(schema_to_ts(&json!({})), "unknown");
    }
}
