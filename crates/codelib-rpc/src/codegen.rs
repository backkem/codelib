/// A `/** ... */` comment, one line per entry, indented; `*/` is defused.
fn doc_comment(out: &mut String, indent: &str, lines: &[String]) {
    let lines: Vec<String> = lines
        .iter()
        .flat_map(|l| {
            l.lines()
                .map(str::trim)
                .map(str::to_owned)
                .collect::<Vec<_>>()
        })
        .filter(|l| !l.is_empty())
        .map(|l| l.replace("*/", "*\\/"))
        .collect();
    match lines.as_slice() {
        [] => {}
        [one] => {
            let _ = writeln!(out, "{indent}/** {one} */");
        }
        many => {
            let _ = writeln!(out, "{indent}/**");
            for l in many {
                let _ = writeln!(out, "{indent} * {l}");
            }
            let _ = writeln!(out, "{indent} */");
        }
    }
}

