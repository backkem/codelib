/// A Markdown API reference: a `## name` section per method with its summary, arguments,
/// result, tags and whether it is async. Arguments and results use the hand-written shape when
/// set, else a TypeScript rendering of the JSON Schema.
pub fn markdown<'a>(methods: impl IntoIterator<Item = &'a MethodInfo>, title: &str) -> String {
    let mut blocks = vec![format!("# {title}")];
    for m in methods {
        blocks.push(format!("## {}", code_span(&m.name)));
        if !m.summary.trim().is_empty() {
            blocks.push(m.summary.trim().to_owned());
        }
        let mut out = String::new();
        let args = m
            .args
            .clone()
            .or_else(|| m.args_schema.as_ref().map(schema_to_ts));
        let returns = m
            .returns
            .clone()
            .or_else(|| m.returns_schema.as_ref().map(schema_to_ts));
        if let Some(a) = args {
            let _ = writeln!(out, "- args: {}", code_span(&a));
        }
        if let Some(r) = returns {
            let _ = writeln!(out, "- returns: {}", code_span(&r));
        }
        if !m.tags.is_empty() {
            let tags: Vec<String> = m.tags.iter().map(|t| code_span(t)).collect();
            let _ = writeln!(out, "- tags: {}", tags.join(", "));
        }
        if m.is_async {
            out.push_str("- async\n");
        }
        if !out.is_empty() {
            blocks.push(out.trim_end().to_owned());
        }
    }
    let mut out = blocks.join("\n\n");
    out.push('\n');
    out
}

/// Inline code that survives backticks and newlines in `s`.
fn code_span(s: &str) -> String {
    let s = s.split_whitespace().collect::<Vec<_>>().join(" ");
    let mut run = 0;
    let mut longest = 0;
    for c in s.chars() {
        if c == '`' {
            run += 1;
            longest = longest.max(run);
        } else {
            run = 0;
        }
    }
    let fence = "`".repeat(longest + 1);
    if longest > 0 {
        format!("{fence} {s} {fence}")
    } else {
        format!("{fence}{s}{fence}")
    }
}

