/// Methods arranged by dotted name: `files.read` lives at `files` -> `read`.
#[derive(Default)]
struct Node<'a> {
    method: Option<&'a MethodInfo>,
    children: Vec<(String, Node<'a>)>,
}

impl<'a> Node<'a> {
    fn build(methods: impl IntoIterator<Item = &'a MethodInfo>) -> Self {
        let mut root = Node::default();
        for m in methods {
            let segments: Vec<&str> = m.name.split('.').collect();
            // A name with empty segments (`a..b`, `.x`) is kept whole rather than split.
            let path: Vec<&str> = if segments.iter().any(|s| s.is_empty()) {
                vec![m.name.as_str()]
            } else {
                segments
            };
            let mut node = &mut root;
            for seg in path {
                let i = match node.children.iter().position(|(k, _)| k == seg) {
                    Some(i) => i,
                    None => {
                        node.children.push((seg.to_owned(), Node::default()));
                        node.children.len() - 1
                    }
                };
                node = &mut node.children[i].1;
            }
            // Duplicate names (only possible with hand-built lists): the first wins.
            if node.method.is_none() {
                node.method = Some(m);
            }
        }
        root
    }

    fn has_hybrid(&self) -> bool {
        self.children
            .iter()
            .any(|(_, n)| (n.method.is_some() && !n.children.is_empty()) || n.has_hybrid())
    }
}

fn is_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    matches!(chars.next(), Some(c) if c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn js_string(s: &str) -> String {
    serde_json::to_string(s).expect("strings always serialize")
}

/// A property key in an object literal or type literal.
fn property_key(key: &str) -> String {
    if key == "__proto__" {
        // `__proto__: value` in a literal sets the prototype; a computed key does not.
        format!("[{}]", js_string(key))
    } else if is_identifier(key) {
        key.to_owned()
    } else {
        js_string(key)
    }
}

/// A member name in a TypeScript type literal. `new(args): R` there is a construct signature,
/// so `new` is quoted.
fn ts_member_key(key: &str) -> String {
    if key == "new" {
        js_string(key)
    } else {
        property_key(key)
    }
}

