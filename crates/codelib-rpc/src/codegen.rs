//! Generated artifacts from method metadata: a JS client prelude, a Markdown API reference and
//! TypeScript declarations.
//!
//! All functions take any iterator of [`MethodInfo`], typically
//! [`Router::methods`](crate::Router::methods), so the output always matches what the router
//! actually serves. Output is deterministic (input order is kept).

use std::collections::HashMap;
use std::fmt::Write as _;

use serde_json::{Map, Value};

use crate::MethodInfo;

/// Options for [`js_client`] and [`typescript`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct JsOptions {
    /// The global the client is installed as (`globalThis.<global>`). Default `"api"`.
    pub global: String,
    /// The call expression each method calls as `<call>(name, args)`. Default `"host.call"`
    /// (the sandbox import: synchronous, takes and returns JS values).
    pub call: String,
    /// TypeScript only: whether methods return a `Promise` (an asynchronous `call`, for example
    /// a browser or network transport). Default `false`.
    pub promise: bool,
}

impl Default for JsOptions {
    fn default() -> Self {
        JsOptions {
            global: "api".to_owned(),
            call: "host.call".to_owned(),
            promise: false,
        }
    }
}

impl JsOptions {
    /// Options installing the client as `globalThis.<global>`, calling `host.call`.
    pub fn new(global: impl Into<String>) -> Self {
        JsOptions {
            global: global.into(),
            ..JsOptions::default()
        }
    }

    /// Sets the call expression.
    pub fn with_call(mut self, call: impl Into<String>) -> Self {
        self.call = call.into();
        self
    }

    /// Sets whether TypeScript methods return a `Promise`.
    pub fn with_promise(mut self, promise: bool) -> Self {
        self.promise = promise;
        self
    }
}

const HEADER: &str = "// Generated by codelib-rpc. Do not edit.\n";

