/// A JavaScript prelude that defines the global `<global>` (via `Object.defineProperty` on
/// `globalThis`, so every name is a plain own property) with one function per method, each
/// returning `<call>(name, args)`.
///
/// Dotted names nest (`files.read` becomes `api.files.read(args)`), names that are not
/// identifiers use quoted keys (`api["frame-fix"](args)`), and a name that is both a method and
/// a namespace (`files` and `files.read`) becomes a function carrying the nested members. The
/// output is a strict-mode IIFE that defines nothing but the global.
pub fn js_client<'a>(
    methods: impl IntoIterator<Item = &'a MethodInfo>,
    opts: &JsOptions,
) -> String {
    let tree = Node::build(methods);
    let call = if opts.call.split('.').all(|seg| is_identifier(seg.trim())) {
        opts.call.trim().to_owned()
    } else {
        format!("({})", opts.call.trim())
    };
    let mut out = String::from(HEADER);
    out.push_str("(function () {\n  \"use strict\";\n");
    if tree.has_hybrid() {
        out.push_str(
            "  const members = (fn, all) => {\n    for (const key of Object.keys(all)) {\n      \
             Object.defineProperty(fn, key, { value: all[key], enumerable: true, writable: true, configurable: true });\n    \
             }\n    return fn;\n  };\n",
        );
    }
    // Not `globalThis.<name> = ...`: for `__proto__` that assignment would replace the global
    // object's prototype instead of defining a global.
    let _ = write!(
        out,
        "  Object.defineProperty(globalThis, {}, {{ value: ",
        js_string(&opts.global)
    );
    js_object(&mut out, &tree, &call, 1);
    out.push_str(", writable: true, configurable: true, enumerable: true });\n})();\n");
    out
}

fn js_object(out: &mut String, node: &Node<'_>, call: &str, depth: usize) {
    if node.children.is_empty() {
        out.push_str("{}");
        return;
    }
    let indent = "  ".repeat(depth + 1);
    out.push_str("{\n");
    for (key, child) in &node.children {
        let key = property_key(key);
        if let Some(m) = child.method {
            doc_comment(out, &indent, std::slice::from_ref(&m.summary));
        }
        match (child.method, child.children.is_empty()) {
            (Some(m), true) => {
                let _ = writeln!(
                    out,
                    "{indent}{key}(args) {{ return {call}({}, args); }},",
                    js_string(&m.name)
                );
            }
            (Some(m), false) => {
                let _ = write!(
                    out,
                    "{indent}{key}: members((args) => {call}({}, args), ",
                    js_string(&m.name)
                );
                js_object(out, child, call, depth + 1);
                out.push_str("),\n");
            }
            (None, _) => {
                let _ = write!(out, "{indent}{key}: ");
                js_object(out, child, call, depth + 1);
                out.push_str(",\n");
            }
        }
    }
    let _ = write!(out, "{}}}", "  ".repeat(depth));
}

