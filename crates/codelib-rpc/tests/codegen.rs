#[test]
fn typescript_without_schemas() {
    let r = small_router();
    let ts = codegen::typescript(r.methods(), &JsOptions::new("cad"));
    let expected = r#"// Generated by codelib-rpc. Do not edit.
declare const cad: {
  /**
   * Add a line
   * args: {start, end, layer?}
   * returns: {id}
   */
  addLine(args?: unknown): unknown;
  /** List files */
  files: {
    (args?: unknown): unknown;
    /**
     * Read a file *\/ with a comment terminator
     * args: {name}
     * returns: string
     */
    read(args?: unknown): unknown;
  };
  /** Fix a frame */
  "frame-fix"(args?: unknown): unknown;
  delete(args?: unknown): unknown;
  /**
   * Every method with its summary, tags, arguments and result.
   * args: {}
   * returns: [{name, summary, tags, args?, returns?, args_schema?, returns_schema?, is_async}]
   */
  methods(args?: unknown): unknown;
};
"#;
    assert_eq!(ts, expected, "\n{ts}");
}

#[test]
fn typescript_with_hand_written_schemas() {
    let mut r = Router::<()>::new();
    r.method("addLine", |_: &mut (), _: ()| Ok(0))
        .summary("Add a line")
        .args_schema_value(json!({
            "type": "object",
            "properties": {
                "end": {"type": "array", "items": {"type": "number"}, "minItems": 2, "maxItems": 2},
                "layer": {"type": ["string", "null"]},
                "start": {"type": "array", "items": {"type": "number"}}
            },
            "required": ["start", "end"]
        }))
        .returns_schema_value(json!({
            "type": "object",
            "properties": {"id": {"type": "integer"}},
            "required": ["id"]
        }));
    r.method("clear", |_: &mut (), _: ()| Ok(()))
        .args_schema_value(json!({"type": "object", "properties": {"all": {"type": "boolean"}}}))
        .returns_schema_value(json!({"type": "null"}));
    let opts = JsOptions::new("1st api").with_promise(true);
    let ts = codegen::typescript(r.methods().filter(|m| m.name != "methods"), &opts);
    let expected = r#"// Generated by codelib-rpc. Do not edit.
declare const _st_api: {
  /** Add a line */
  addLine(args: { end: [number, number]; layer?: string | null; start: number[] }): Promise<{ id: number }>;
  clear(args?: { all?: boolean }): Promise<null>;
};
"#;
    assert_eq!(ts, expected, "\n{ts}");
}
