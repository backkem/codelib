//! JSON Schemas from `schemars` (feature `schema`) and what codegen makes of them.
#![cfg(feature = "schema")]

use codelib_rpc::codegen::{self, JsOptions};
use codelib_rpc::{Failure, Router, schema_value};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use serde_json::json;

// Fields in alphabetical order, so the snapshots do not depend on serde_json's
// `preserve_order` feature being enabled somewhere in the build.
#[derive(Deserialize, JsonSchema)]
#[allow(dead_code)]
struct AddLine {
    /// End point.
    end: [f64; 2],
    kind: Option<Kind>,
    layer: Option<String>,
    start: [f64; 2],
}

#[derive(Deserialize, Serialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
enum Kind {
    Solid,
    Dashed,
}

#[derive(Serialize, JsonSchema)]
struct Created {
    id: u64,
    tags: Vec<String>,
}

#[derive(Deserialize, JsonSchema, Default)]
#[allow(dead_code)]
struct Clear {
    #[serde(default)]
    all: bool,
}

fn router() -> Router<Vec<u64>> {
    let mut r = Router::<Vec<u64>>::new();
    r.method("addLine", |ids: &mut Vec<u64>, _: AddLine| {
        ids.push(ids.len() as u64);
        Ok(Created {
            id: ids.len() as u64 - 1,
            tags: vec![],
        })
    })
    .summary("Add a line")
    .schema();
    r.method("clear", |ids: &mut Vec<u64>, _: Clear| {
        ids.clear();
        Ok(())
    })
    .schema();
    r.method("count", |ids: &mut Vec<u64>, _: ()| Ok(ids.len()))
        .returns("number")
        .schema();
    r.method_async_boxed("kinds", |_: &mut Vec<u64>, _: ()| {
        Box::pin(async { Ok::<_, Failure>(vec![Kind::Solid, Kind::Dashed]) })
    })
    .returns_schema();
    r
}

#[test]
fn schemas_are_attached() {
    let r = router();
    let info = r.method_info("addLine").unwrap();
    let args = info.args_schema.as_ref().unwrap();
    assert!(args.get("$schema").is_none(), "{args}");
    assert_eq!(args["type"], "object");
    assert_eq!(args["required"], json!(["end", "start"]));
    assert_eq!(args["properties"]["end"]["description"], "End point.");
    assert_eq!(
        info.returns_schema.as_ref().unwrap()["required"],
        json!(["id", "tags"])
    );
    assert!(r.method_info("kinds").unwrap().args_schema.is_none());
    assert!(r.method_info("kinds").unwrap().returns_schema.is_some());
    assert_eq!(schema_value::<u32>()["type"], "integer");

    // The schemas travel with the built-in `methods`.
    let out = r.call_json_sync(&mut vec![], "methods", "").unwrap();
    let list: serde_json::Value = serde_json::from_str(&out).unwrap();
    assert_eq!(list[0]["args_schema"], *args);
}

#[test]
fn typescript_from_schemas() {
    let r = router();
    let ts = codegen::typescript(r.methods(), &JsOptions::new("cad"));
    let expected = r#"// Generated by codelib-rpc. Do not edit.
declare const cad: {
  /** Add a line */
  addLine(args: { end: [number, number]; kind?: "solid" | "dashed" | null; layer?: string | null; start: [number, number] }): { id: number; tags: string[] };
  clear(args?: { all?: boolean }): null;
  /** returns: number */
  count(args?: null): number;
  kinds(args?: unknown): ("solid" | "dashed")[];
  /**
   * Every method with its summary, tags, arguments and result.
   * args: {}
   * returns: [{name, summary, tags, args?, returns?, args_schema?, returns_schema?, is_async}]
   */
  methods(args?: unknown): unknown;
};
"#;
    assert_eq!(ts, expected, "\n{ts}");
}

#[test]
fn markdown_falls_back_to_schema_types() {
    let r = router();
    let md = codegen::markdown(r.methods().take(3), "API");
    let expected = "# API

## `addLine`

Add a line

- args: `{ end: [number, number]; kind?: \"solid\" | \"dashed\" | null; layer?: string | null; start: [number, number] }`
- returns: `{ id: number; tags: string[] }`

## `clear`

- args: `{ all?: boolean }`
- returns: `null`

## `count`

- args: `null`
- returns: `number`
";
    assert_eq!(md, expected, "\n{md}");
}
